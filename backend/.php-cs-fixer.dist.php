<?php

$plugins = is_dir('/plugins') ? '/plugins' : dirname(__DIR__).'/plugins';

$finder = (new PhpCsFixer\Finder())
    ->in(__DIR__)
    ->notPath('config/reference.php') // Auto-generated by Symfony Flex (composer scripts)
    ->exclude('var')
    ->exclude('src/Grpc/Triton') // Generated protobuf files - DO NOT FORMAT
    ->exclude('lib/grpc') // Generated protobuf files - DO NOT FORMAT
;

if (is_dir($plugins)) {
    $finder->in($plugins)->notPath('#/(frontend|migrations)(/|$)#');
}

return (new PhpCsFixer\Config())
    ->setRules([
        '@Symfony' => true,
    ])
    ->setFinder($finder)
;
