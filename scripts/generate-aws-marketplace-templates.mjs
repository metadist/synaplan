#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

const sourceTemplates = [
  'synaplan-new-vpc.yaml',
  'synaplan-existing-vpc.yaml',
]

const architectures = {
  x86_64: {
    defaultInstanceType: 'm7i.xlarge',
    instanceTypes: ['c7i.xlarge', 'm7i.xlarge', 'm7i.2xlarge'],
    description:
      'Synaplan needs at least 4 vCPU and 8 GB of memory. These instance types require the x86_64 Marketplace AMI.',
  },
  arm64: {
    defaultInstanceType: 'm7g.xlarge',
    instanceTypes: ['c7g.xlarge', 'm7g.xlarge', 'm7g.2xlarge'],
    description:
      'Synaplan needs at least 4 vCPU and 8 GB of memory. These Graviton instance types require the arm64 Marketplace AMI.',
  },
}

const generatedNotice = [
  '# Generated by scripts/generate-aws-marketplace-templates.mjs.',
  '# Do not edit this file directly; update the source template and regenerate.',
].join('\n')

const wrapDescription = (description) => {
  const words = description.split(' ')
  const lines = []
  let line = ''

  for (const word of words) {
    if (`${line} ${word}`.trim().length > 76) {
      lines.push(line)
      line = word
    } else {
      line = `${line} ${word}`.trim()
    }
  }
  if (line) lines.push(line)

  return lines.map((value) => `      ${value}`).join('\n')
}

const replaceInstanceTypeParameter = (template, architecture) => {
  const start = template.indexOf('\n  InstanceType:\n')
  const end = template.indexOf('\n  DataVolumeSize:\n', start)

  if (start === -1 || end === -1) {
    throw new Error('Could not locate the InstanceType parameter block')
  }

  const allowedValues = architecture.instanceTypes
    .map((instanceType) => `      - ${instanceType}`)
    .join('\n')
  const replacement = `
  InstanceType:
    Type: String
    Default: ${architecture.defaultInstanceType}
    AllowedValues:
${allowedValues}
    Description: >-
${wrapDescription(architecture.description)}
`

  return `${template.slice(0, start)}${replacement}${template.slice(end)}`
}

const generateTemplate = (source, architecture) => {
  const withArchitecture = replaceInstanceTypeParameter(source, architecture)
  return withArchitecture.replace(
    "AWSTemplateFormatVersion: '2010-09-09'\n",
    `AWSTemplateFormatVersion: '2010-09-09'\n${generatedNotice}\n`,
  )
}

let stale = false

for (const sourceTemplate of sourceTemplates) {
  const sourcePath = resolve(
    repoRoot,
    'deploy/aws/cloudformation',
    sourceTemplate,
  )
  const source = await readFile(sourcePath, 'utf8')

  for (const [architectureName, architecture] of Object.entries(
    architectures,
  )) {
    const outputPath = resolve(
      repoRoot,
      'deploy/aws/marketplace',
      architectureName,
      sourceTemplate,
    )
    const generated = generateTemplate(source, architecture)

    if (checkOnly) {
      let current = ''
      try {
        current = await readFile(outputPath, 'utf8')
      } catch {
        // Report the same actionable stale-output error for a missing file.
      }
      if (current !== generated) {
        console.error(
          `${outputPath} is stale; run node scripts/generate-aws-marketplace-templates.mjs`,
        )
        stale = true
      }
      continue
    }

    await mkdir(dirname(outputPath), { recursive: true })
    await writeFile(outputPath, generated)
    console.log(`Generated ${outputPath}`)
  }
}

if (stale) process.exit(1)
